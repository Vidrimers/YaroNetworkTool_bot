#!/bin/bash

###############################################################################
# kvn-bot-stop.sh - Остановка Telegram бота
# Использование: ./bot/kvn-bot-stop.sh
###############################################################################

echo "[STOP] Остановка Telegram бота..."
pm2 stop vpn-bot || exit 1

echo "[STOP] ✓ Бот остановлен"
echo "[STOP] Проверить статус: pm2 status"
echo "[STOP] Запустить снова: pm2 start vpn-bot"

exit 0
